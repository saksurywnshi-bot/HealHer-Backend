"""Prohibited Diagnostic Terms Configuration.

Mental Health Reflection Guardrail:
The reflection generated by the AI must gently mirror the user's feelings without
making medical diagnoses, labeling disorders, or using clinical diagnostic language.

Rule:
If any of these substrings appear in the reflection sentence, the output is rejected.
The model is retried once with stricter instructions. If it fails again,
status: 'unavailable' is returned to the client.
"""

from typing import List

PROHIBITED_DIAGNOSTIC_TERMS: List[str] = [
    # English terms
    "you have",
    "diagnos",
    "disorder",
    "depress",
    "clinical",
    "bipolar",
    "schizo",
    "syndrome",
    "pathology",
    "prescription",
    "medication",
    "medical condition",
    "mental illness",
    # Hindi terms
    "निदान",
    "रोग",
    "बीमारी",
    "विकार",
    "डिप्रेशन है",
    "दवा",
    # Bengali terms
    "রোগ",
    "অসুস্থতা",
    "নির্ণয়",
    "ডিপ্রেশন আছে",
    # Tamil terms
    "நோய்",
    "மருத்துவக் கண்டறிதல்",
    "மனச்சோர்வு உள்ளது",
    "மருந்து",
]


def contains_diagnostic_terms(text: str) -> bool:
    """Check if the text contains any prohibited diagnostic phrases."""
    if not text:
        return False
    normalized = text.lower()
    for term in PROHIBITED_DIAGNOSTIC_TERMS:
        if term.lower() in normalized:
            return True
    return False
