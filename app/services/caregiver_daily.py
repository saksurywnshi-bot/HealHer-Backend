def format_caregiver_tip(tip: Dict[str, Any], language: str = "en") -> Dict[str, str]:
    """Format raw tip item into client response structure:
    {id, kind, kind_label_key, text, text_language}.
    """
    kind = tip.get("kind", "do")
    lang_key = f"text_{language}"
    localized_text = tip.get(lang_key)

    tip_id = tip.get("id", "")
    if (not localized_text or not isinstance(localized_text, str) or not localized_text.strip()) and language in ("hi", "bn", "ta"):
        matched_dict = CAREGIVER_TIPS_TRANSLATED.get(tip_id, {})
        if matched_dict.get(language):
            localized_text = matched_dict[language]

    if localized_text and isinstance(localized_text, str) and localized_text.strip():
        text = localized_text.strip()
        text_lang = language
    else:
        text = tip.get("text_en", "").strip()
        text_lang = "en"

    return {
        "id": tip_id,
        "kind": kind,
        "kind_label_key": f"caregiver.kind.{kind}",
        "text": text,
        "text_language": text_lang,
    }


def get_daily_caregiver_tips(
    stage: str,
    user_ref: str,
    language: str = "en",
    result_state: str = "keep_supporting",
    flags: Iterable[str] = (),
    day: Optional[date] = None,
    record_history: bool = True,
    n: int = CAREGIVER_DAILY_COUNT,
) -> Tuple[List[Dict[str, str]], str]:
    """Primary service entrypoint for caregiver daily tips.

    Returns:
        (formatted_tips_list, library_version_hash)
    """
    lib = get_served_caregiver_library()
    version_hash = get_caregiver_library_version_hash()
    local_day = day or get_kolkata_today()

    if result_state == "get_help_today":
        return [], version_hash

    # Fetch user's tip history
    history = get_user_tip_history(user_ref)

    # Select tips
    raw_chosen = select_daily_tips(
        lib=lib,
        stage=stage,
        user_ref=user_ref,
        day=local_day,
        history=history,
        result_state=result_state,
        flags=flags,
        n=n,
    )

    # Record to database once per day per user (idempotent)
    if record_history and raw_chosen:
        tip_ids = [t["id"] for t in raw_chosen]
        record_shown_tips(user_ref, tip_ids, local_day)

    # Format localized response
    formatted = [format_caregiver_tip(t, language) for t in raw_chosen]
    return formatted, version_hash
