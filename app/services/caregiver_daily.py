AWARE: Set[str] = {"notice", "avoid", "self_care", "clinician"}
LIGHT: Set[str] = {"small_joy", "try_together"}
CAPS: Dict[str, int] = {
    "self_care": 1,
    "clinician": 1,
    "notice": 1,
    "avoid": 1,
    "say": 2,
    "do": 3,
    "check_in": 1,
}

_CONFIG_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "config",
    "caregiver_flags.json",
)


def load_flag_themes() -> Dict[str, Set[str]]:
    """Load questionnaire risk area to favoured themes mapping from config."""
    default_mapping = {
        "money_food": {"share_chores", "ask_others"},
        "tension": {"calm_home"},
        "isolated": {"help_her_connect"},
        "baby_hard": {"share_baby_care"},
        "no_support": {"ask_others", "share_chores", "help_her_connect"},
        "signs_high": {"appointments", "start_conversation", "notice_changes"},
    }
    if os.path.exists(_CONFIG_PATH):
        try:
            with open(_CONFIG_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)
                res: Dict[str, Set[str]] = {}
                for k, v in data.items():
                    if k.startswith("_"):
                        continue
                    if isinstance(v, list):
                        res[k] = set(v)
                return res or default_mapping
        except Exception as e:
            logger.warning("Could not read caregiver_flags.json: %s", e)
    return default_mapping


def get_kolkata_today() -> date:
    """Return today's date in Asia/Kolkata timezone (UTC+5:30)."""
    try:
        from zoneinfo import ZoneInfo
        return datetime.now(ZoneInfo("Asia/Kolkata")).date()
    except Exception:
        return datetime.now(timezone(timedelta(hours=5, minutes=30))).date()


def _rank(user_ref: str, stage: str, day: date, key: str) -> int:
    """Deterministic integer pseudo-random rank based on SHA-256."""
    h = hashlib.sha256(f"{user_ref}|{stage}|{day.isoformat()}|{key}".encode("utf-8")).hexdigest()
    return int(h[:12], 16)


def select_daily_tips(
    lib: Optional[Any] = None,
    stage: str = "prenatal",
    user_ref: str = "user",
    day: Optional[date] = None,
    history: Optional[Dict[str, date]] = None,
    result_state: str = "keep_supporting",
    flags: Iterable[str] = (),
    n: int = CAREGIVER_DAILY_COUNT,
    recency_days: int = CAREGIVER_RECENCY_DAYS,
    served: Optional[List[Dict[str, Any]]] = None,
) -> List[Dict[str, Any]]:
    """Select daily tips matching exact rules from daily_selector_reference.txt.

    Returns raw tip dictionaries from the library.
    """
    if result_state == "get_help_today":
        return []

    local_day = day or get_kolkata_today()
    hist = history or {}
    flag_themes_map = load_flag_themes()

    # Pool = served tips where stage equals user stage or 'both'
    if served is not None:
        pool = [i for i in served if i.get("stage") in (stage, "both")]
    elif isinstance(lib, list):
        pool = [i for i in lib if i.get("stage") in (stage, "both")]
    else:
        if lib is None:
            lib = get_served_caregiver_library()
        pool = [
            i for i in lib.get("suggestions", [])
            if i.get("status") == "approved" or i.get("_serve_draft")
        ]
        pool = [i for i in pool if i.get("stage") in (stage, "both")]

    # Compute favoured themes
    want: Set[str] = set()
    if flags:
        for f in flags:
            want.update(flag_themes_map.get(f, set()))
    if result_state == "talk_soon":
        want.update({"appointments", "start_conversation"})

    def age(item: Dict[str, Any]) -> int:
        last = hist.get(item.get("id", ""))
        return 10**6 if last is None else (local_day - last).days

    def sort_key(item: Dict[str, Any]) -> Tuple[bool, int, bool, int]:
        item_id = item.get("id", "")
        item_themes = set(item.get("themes", []))
        is_recent = age(item) < recency_days
        recent_age_penalty = -age(item) if is_recent else 0
        matches_want = bool(want & item_themes)
        return (
            is_recent,
            recent_age_penalty,
            not matches_want,
            _rank(user_ref, stage, local_day, item_id),
        )

    cand = sorted(pool, key=sort_key)

    chosen: List[Dict[str, Any]] = []
    kinds: Dict[str, int] = {}
    themes: Set[str] = set()

    def light_count() -> int:
        return sum(kinds.get(k, 0) for k in LIGHT)

    def ok(item: Dict[str, Any]) -> bool:
        if item in chosen:
            return False
        item_themes = item.get("themes", [])
        first_theme = item_themes[0] if item_themes else None
        if first_theme and first_theme in themes:
            return False
        k = item.get("kind", "")
        if kinds.get(k, 0) >= CAPS.get(k, 99):
            return False
        if k in LIGHT and light_count() >= 2:
            return False
        return True

    def add(item: Dict[str, Any]) -> None:
        chosen.append(item)
        k = item.get("kind", "")
        kinds[k] = kinds.get(k, 0) + 1
        item_themes = item.get("themes", [])
        if item_themes:
            themes.add(item_themes[0])

    def take(pred) -> bool:
        for item in cand:
            if pred(item) and ok(item):
                add(item)
                return True
        return False

    # 1. Favoured topic first (talk_soon, flagged areas)
    if want:
        take(lambda item: bool(want & set(item.get("themes", []))))

    # 2. Daily mix: check_in, one light kind, one do, one say
    if not kinds.get("check_in"):
        take(lambda item: item.get("kind") == "check_in")
    if light_count() == 0:
        take(lambda item: item.get("kind") in LIGHT)
    if not kinds.get("do"):
        take(lambda item: item.get("kind") == "do")
    if not kinds.get("say"):
        take(lambda item: item.get("kind") == "say")

    # 3. Wildcard: seeded coin picks "aware" kinds (notice, avoid, self_care, clinician) or any kind
    if len(chosen) < n:
        if _rank(user_ref, stage, local_day, "wild") % 2 == 0 and not any(c.get("kind") in AWARE for c in chosen):
            take(lambda item: item.get("kind") in AWARE)
        # Fill remaining slots up to n
        for item in cand:
            if len(chosen) >= n:
                break
            if ok(item):
                add(item)

    # 4. Final display order: seeded shuffle with the same seed
    r = random.Random(_rank(user_ref, stage, local_day, "order"))
    r.shuffle(chosen)
    return chosen


