"""Caregiver 'How you can help her today' Daily Tip Selection (v0.2).

Plain code, zero AI invocation.
Strictly adheres to daily_selector_reference.txt:
1. Returns [] if result_state == 'get_help_today'.
2. Filters by stage ('prenatal' | 'postnatal' | 'both').
3. Favoured themes via config (talk_soon -> appointments, start_conversation; extra_support -> flags).
4. Daily mix:
   - Favoured topic first if requested
   - One kind 'check_in'
   - One kind 'small_joy' or 'try_together'
   - One kind 'do'
   - One kind 'say'
   - Wildcard: seeded coin picks notice, avoid, self_care, or clinician if none present, else any kind
   - Fill to daily count (5)
5. Caps:
   - at most 1 each of self_care, clinician, notice, avoid, check_in
   - at most 2 of 'say'
   - at most 3 of 'do'
   - at most 2 of small_joy + try_together together
   - no two tips with same first theme
   - never repeat tip id
6. Deterministic seeded shuffle with SHA-256(user_ref | stage | day | order).
7. Local date in Asia/Kolkata timezone.
8. History recency: items not shown in last CAREGIVER_RECENCY_DAYS first; among recent, oldest first.
"""

