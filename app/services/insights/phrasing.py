
"""BEAM Phrasing Layer, Output Validator, and Deterministic Fallback Template Generator.

Constraints:
- The language model ONLY rewrites pre-computed facts warmly in English.
- The model NEVER decides alert tiers, NEVER adds unapproved advice, NEVER mentions medication, NEVER diagnoses.
- Strict Output Validator: scans for diagnosis words, medication names, unapproved statistics, or alarming labels.
- Deterministic Fallback: automatically builds a compassionate, high-quality message directly from the
  approved suggestions library if the validator fails or if the local model is offline/unavailable.
- Tier 3 text is NEVER passed to or generated by the language model.
"""

import logging
import os
import re
import urllib.request
import json
from typing import Any, Dict, List, Optional, Tuple

from app.services.insights.config_loader import get_beam_rules_config, get_beam_suggestions_config

logger = logging.getLogger("healher_backend.insights.phrasing")

OLLAMA_URL = os.environ.get("OLLAMA_URL", "http://localhost:11434")
OLLAMA_MODEL = os.environ.get("OLLAMA_MODEL", "qwen3:8b")

DISALLOWED_DIAGNOSIS_WORDS = {
    "depression", "depressive", "bipolar", "mania", "manic", "hypomania",
    "psychosis", "psychotic", "schizophrenia", "disorder", "syndrome", "pathology",
}

DISALLOWED_MEDICATIONS = {
    "medication", "medicine", "medications", "medicines", "meds", "pill", "pills", "drug", "drugs",
    "sertraline", "fluoxetine", "paroxetine", "escitalopram", "citalopram", "fluvoxamine",
    "venlafaxine", "duloxetine", "bupropion", "mirtazapine", "lithium", "quetiapine",
    "olanzapine", "aripiprazole", "haloperidol", "risperidone", "valproate", "lamotrigine",
    "clonazepam", "lorazepam", "alprazolam", "diazepam", "ssri", "snri", "antidepressant",
    "antipsychotic", "mood stabilizer", "sedative",
}

DISALLOWED_ALARM_WORDS_BELOW_TIER3 = {
    "danger", "dangerous", "crisis", "emergency", "severe depressed", "severe elevated"
}


def validate_model_output(text: str, tier: int = 0) -> Tuple[bool, List[str]]:
    """Validate that language model output strictly adheres to safety and tone rules."""
    violations: List[str] = []
    lower_text = text.lower()
    words = set(re.findall(r"\b[a-z\-]+\b", lower_text))

    # 1. Check diagnosis words
    for word in DISALLOWED_DIAGNOSIS_WORDS:
        if word in words:
            violations.append(f"Forbidden diagnosis word detected: '{word}'")

    # 2. Check medication words
    for med in DISALLOWED_MEDICATIONS:
        if med in lower_text:
            violations.append(f"Forbidden medication mention detected: '{med}'")

    # 3. Check alarm words below Tier 3
    if tier < 3:
        for alarm in DISALLOWED_ALARM_WORDS_BELOW_TIER3:
            if alarm in lower_text:
                violations.append(f"Alarming term detected below Tier 3: '{alarm}'")

    return len(violations) == 0, violations


def build_fallback_template(
    evaluation_result: Dict[str, Any],
    suggestions: List[Dict[str, Any]],
    phase: str = "pregnancy",
) -> Dict[str, Any]:
    """Generate a clean, deterministic message built strictly from pre-approved config texts.

    Follows the 11 tone rules in Section 7:
    - Describe patterns not labels
    - Normalise first
    - Strengths first
    - One clear next step
    - Hope and giving control
    - Permanent disclaimer line
    """
    rules_cfg = get_beam_rules_config()
    sugg_cfg = get_beam_suggestions_config()
    scripts = rules_cfg.get("tier_scripts", {})

    band = evaluation_result.get("weekly_band", "okay_mixed")
    tier = evaluation_result.get("tier", 0)

    # If not enough data
    if band == "not_enough_data":
        return {
            "title": "Weekly Check-in",
            "opening": scripts.get("not_enough_data_script", "We'd love to see a bit more of your week. A quick daily check-in makes these insights more useful."),
            "strength": None,
            "sleep_note": None,
            "pattern_note": None,
            "suggestions": [s.get("text") for s in suggestions],
            "tier_message": None,
            "tier": tier,
            "disclaimer": "This app does not diagnose. If you are worried, please speak to a doctor.",
            "source": "deterministic_template",
        }

    # Openings by band
    band_key = "okay"
    if band == "good_balanced":
        band_key = "good"
    elif band == "tougher_low":
        band_key = "tougher"
    elif band in ("high_energy", "mixed_swings"):
        band_key = "high_energy"

    openings_list = sugg_cfg.get("openings", {}).get(band_key, [])
    opening = openings_list[0] if openings_list else "Thank you for checking in with yourself this week."

    strength = evaluation_result.get("weekly_strength") or "Showing care for yourself by taking a moment to reflect."

    # Sleep note
    m_sum = evaluation_result.get("monthly_summary", {})
    avg_sleep = m_sum.get("average_sleep_hours")
    sleep_note = None
    if avg_sleep:
        sleep_note = f"Your sleep has averaged about {avg_sleep} hours a night."
    else:
        sleep_note = "Rest when you can throughout the day."

    # Pattern note
    addon = evaluation_result.get("weekly_addon")
    pattern_note = None
    if addon == "anxious_or_irritable":
        pattern_note = "A few days this week brought extra tension or irritability, which is common when tired."

    # Tier message
    tier_msg = None
    if tier == 1:
        tier_msg = scripts.get("tier1_script")
    elif tier == 2:
        if evaluation_result.get("elevated_side_flagged"):
            tier_msg = scripts.get("tier2_elevated_script")
        else:
            tier_msg = scripts.get("tier2_depressed_script")
    elif tier == 3:
        tier_msg = scripts.get("tier3_urgent_script")

    return {
        "title": f"Your Weekly Insights ({band.replace('_', ' ').title()})",
        "opening": opening,
        "strength": strength,
        "sleep_note": sleep_note,
        "pattern_note": pattern_note,
        "suggestions": [s.get("text") for s in suggestions],
        "tier_message": tier_msg,
        "tier": tier,
        "disclaimer": "This app does not diagnose. If you are worried, please speak to a doctor.",
        "source": "deterministic_template",
    }


def query_ollama_phrasing(prompt: str) -> Optional[str]:
    """Query local Ollama instance for conversational rephrasing."""
    try:
        req_data = json.dumps({
            "model": OLLAMA_MODEL,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": 0.3,
                "top_p": 0.9,
            }
        }).encode("utf-8")

        req = urllib.request.Request(
            f"{OLLAMA_URL}/api/generate",
            data=req_data,
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=5) as response:
            if response.status == 200:
                resp_json = json.loads(response.read().decode("utf-8"))
                return resp_json.get("response", "").strip()
    except Exception as e:
        logger.info("Ollama phrasing not reachable (%s), using deterministic template fallback.", str(e))
        return None
    return None


def generate_phrased_insights(
    evaluation_result: Dict[str, Any],
    suggestions: List[Dict[str, Any]],
    phase: str = "pregnancy",
    use_llm: bool = True,
) -> Dict[str, Any]:
    """Generate warm, validated weekly insights using local LLM with fallback to approved template.

    Tier 3 messages NEVER pass through the language model.
    """
    tier = evaluation_result.get("tier", 0)

    # Tier 3 is strictly pre-approved script
    if tier == 3:
        return build_fallback_template(evaluation_result, suggestions, phase)

    # Always generate the verified fallback template first
    fallback = build_fallback_template(evaluation_result, suggestions, phase)

    if not use_llm:
        return fallback

    # If evaluation was not enough data, use template directly
    if evaluation_result.get("weekly_band") == "not_enough_data":
        return fallback

    # Construct strict prompt for local Ollama/Qwen model
    suggestion_texts = "\n".join(f"- {s['text']}" for s in suggestions)
    prompt = f"""You are a compassionate, gentle perinatal assistant helping a mother.
Rewrite the following facts and approved suggestions into a warm, supportive 2-3 sentence summary.

FACTS:
- Weekly Band: {evaluation_result.get('weekly_band')}
- Strength: {fallback.get('strength')}
- Sleep: {fallback.get('sleep_note')}
- Suggestions:
{suggestion_texts}

STRICT SAFETY RULES:
1. Do NOT diagnose any condition. Do NOT use the words 'depression', 'bipolar', 'mania', 'psychosis', or 'disorder'.
2. Do NOT mention any medications or pills.
3. Do NOT add new medical advice or numbers beyond what is provided above.
4. Keep the tone warm, validating, and hopeful.

Rewritten summary:"""

    raw_response = query_ollama_phrasing(prompt)
    if not raw_response:
        return fallback

    is_valid, violations = validate_model_output(raw_response, tier=tier)
    if not is_valid:
        logger.warning("Model output failed validation (%s), falling back to template.", violations)
        return fallback

    # Validated response
    return {
        "title": fallback["title"],
        "opening": raw_response,
        "strength": fallback["strength"],
        "sleep_note": fallback["sleep_note"],
        "pattern_note": fallback["pattern_note"],
        "suggestions": fallback["suggestions"],
        "tier_message": fallback["tier_message"],
        "tier": tier,
        "disclaimer": fallback["disclaimer"],
        "source": "ollama_validated",
    }
